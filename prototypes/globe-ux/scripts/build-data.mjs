// PROTOTYPE data build. Usage: node scripts/build-data.mjs <dir with geoBoundaries ADM1 *_simplified geojson named ISO3.geojson>
// Writes assets/data/*.json, assets/regions/<ISO3>.json and src/regionIndex.ts.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..');
const rawDir = process.argv[2];
if (!rawDir) throw new Error('pass the geoBoundaries download dir');

const iso = require('i18n-iso-countries');
iso.registerLocale(require('i18n-iso-countries/langs/fr.json'));

const dataDir = path.join(root, 'assets', 'data');
const regDir = path.join(root, 'assets', 'regions');
fs.mkdirSync(dataDir, { recursive: true });
fs.mkdirSync(regDir, { recursive: true });

for (const res of ['50m', '110m']) {
  fs.copyFileSync(require.resolve(`world-atlas/countries-${res}.json`), path.join(dataDir, `world-${res}.json`));
}

const world = require('world-atlas/countries-50m.json');
const countries = {};
for (const g of world.objects.countries.geometries) {
  if (!g.id) continue;
  const a3 = iso.numericToAlpha3(g.id);
  countries[g.id] = { iso3: a3, name: iso.getName(a3, 'fr') || g.properties.name };
}
fs.writeFileSync(path.join(dataDir, 'countries.json'), JSON.stringify(countries));

const mapshaper = path.join(root, 'node_modules', 'mapshaper', 'bin', 'mapshaper');
const built = [];
let total = 0;
for (const f of fs.readdirSync(rawDir).filter((f) => f.endsWith('.geojson')).sort()) {
  const a3 = path.basename(f, '.geojson');
  const out = path.join(regDir, `${a3}.json`);
  try {
    execFileSync(process.execPath, [mapshaper, '-i', path.join(rawDir, f),
      '-filter-fields', 'shapeName,shapeID', '-rename-fields', 'name=shapeName,id=shapeID',
      '-simplify', '20%', 'keep-shapes',
      '-o', out, 'format=topojson', 'quantization=100000', 'force'], { stdio: 'pipe' });
    built.push(a3);
    total += fs.statSync(out).size;
  } catch (e) {
    console.warn('skip', a3, String(e.stderr || e).slice(0, 200));
  }
}

const lines = built.map((a3) => `  ${a3}: () => require('../assets/regions/${a3}.json'),`);
fs.writeFileSync(path.join(root, 'src', 'regionIndex.ts'),
  `// GENERATED by scripts/build-data.mjs (PROTOTYPE)\nexport const REGIONS: Record<string, () => any> = {\n${lines.join('\n')}\n};\n`);
console.log(`regions: ${built.length} countries, ${(total / 1e6).toFixed(1)} MB`);
